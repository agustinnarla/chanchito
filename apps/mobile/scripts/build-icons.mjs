// Generates src/components/icons.ts with the Material Symbols Rounded (Apache 2.0) paths the app
// uses, like apps/web/scripts/build-icons.mjs.
// Add a name to ICONS and run `pnpm --filter @chanchito/mobile icons`.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const ICONS = [
  'add',
  'check',
  'chevron_left',
  'chevron_right',
  'close',
  'delete',
  'error',
  'event',
  'logout',
  'more_vert',
  'visibility',
  'visibility_off',
]

const require = createRequire(import.meta.url)
const root = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded')
const path = (file) => readFileSync(join(root, file), 'utf8').match(/<path d="([^"]+)"/)[1]

const entries = ICONS.map(
  (name) => `  ${name}: ['${path(`${name}.svg`)}', '${path(`${name}-fill.svg`)}'],`,
)
const out = new URL('../src/components/icons.ts', import.meta.url)
writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from @material-symbols/svg-400 (Apache 2.0). Don't edit.
// Each icon: [outlined path, filled path], in a "0 -960 960 960" viewBox.
export const ICON_PATHS = {
${entries.join('\n')}
} as const satisfies Record<string, readonly [string, string]>

export type IconName = keyof typeof ICON_PATHS
`,
)
console.log(`${ICONS.length} íconos generados.`)
